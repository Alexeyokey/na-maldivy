#!/usr/bin/env python3
"""Generate application labels from the public D5 catalogue, without a network."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.tools.destinations import load_catalogue  # noqa: E402


def outputs():
    catalogue = ROOT / "data/destinations.yaml"
    names = {row.iata: row.name for row in sorted(load_catalogue(catalogue).destinations, key=lambda row: row.iata)}
    digest = hashlib.sha256(catalogue.read_bytes()).hexdigest()
    python = (
        '"""Generated by scripts/build_destination_names.py from public D5 labels."""\n\n'
        + f'SOURCE_SHA256 = "{digest}"\n'
        + "DESTINATION_NAMES = {\n"
        + "".join(f"    {json.dumps(code)}: {json.dumps(name, ensure_ascii=False)},\n" for code, name in names.items())
        + "}\n"
    )
    javascript = (
        "/** Generated from the public D5 catalogue; labels do not confirm inventory. */\n"
        + f"export const sourceSha256={json.dumps(digest)};\n"
        + "export const destinationNames=Object.freeze("
        + json.dumps(names, ensure_ascii=False, separators=(",", ":"))
        + ");\nexport const destinationCodes=Object.freeze(Object.keys(destinationNames));\n"
    )
    return {
        ROOT / "backend/app/agent/destination_names.py": python.encode(),
        ROOT / "frontend/dist/destination-names.generated.js": javascript.encode(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    drift = []
    for path, expected in outputs().items():
        if path.is_file() and path.read_bytes() == expected:
            continue
        if args.check:
            drift.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_bytes(expected)
    print(
        json.dumps(
            {
                "status": "failed" if drift else "passed",
                "drift": drift,
                "network_calls": 0,
            }
        )
    )
    return int(bool(drift))


if __name__ == "__main__":
    raise SystemExit(main())
